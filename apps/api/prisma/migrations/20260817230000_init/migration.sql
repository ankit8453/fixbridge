-- Initial schema — one migration, squashed from the 14 that built Phases 1-12.
--
-- ## Why this is a squash and not a fifteenth migration
--
-- The old migration #1 began `CREATE EXTENSION postgis`, and the production
-- host cannot provide it: its PostgreSQL is aaPanel's source-compiled build at
-- /www/server/pgsql, whose extension directory contains neither `postgis` nor
-- `btree_gist`. (`apt install postgresql-16-postgis-3` installs into
-- /usr/share/postgresql/, which that server never reads — it appears to succeed
-- and changes nothing.) So every deploy would have failed on statement one,
-- and a migration that converted geography columns *afterwards* could never run
-- either. The history had to collapse.
--
-- Squashing was safe here because no database had been deployed yet: the target
-- had zero tables and no `_prisma_migrations` row. The 14 original files remain
-- in git history.
--
-- ## What changed from those 14
--
--   1. `geography(Point, 4326)` columns became plain doubles:
--        addresses.location          -> addresses.lat / addresses.lng
--        provider_profiles.base_location -> base_lat / base_lng
--      Distance is computed with haversine SQL generated by
--      `src/core/geo-sql.ts`, which is also where the PostGIS path lives if a
--      future host supports it. Accuracy cost: ~0.3% (about 15 m over 5 km).
--
--   2. The two GiST spatial indexes are gone. Radius queries pre-filter with a
--      lat/lng bounding box, which ordinary B-tree indexes DO accelerate, then
--      compute exact distance on the survivors. At one city this is fast; it
--      would not be at national scale.
--
--   3. The double-booking guard changed shape. It was:
--        EXCLUDE USING gist (provider_id WITH =, time_range WITH &&)
--          WHERE (status IN ('held','booked'))
--      which needs btree_gist. It is now a partial UNIQUE INDEX on
--      (provider_id, starts_at) with the same WHERE clause, and the derived
--      `time_range` column and its trigger are gone with it.
--
--      Equivalent here because slots are generated on a fixed grid from
--      availability templates (`slot-plan.ts`: dayStart + n * incrementMinutes),
--      so two live slots for one provider can only collide on an identical
--      starts_at. It does NOT catch arbitrary overlapping ranges — if slots ever
--      become caller-timed, the exclusion constraint must come back, and that
--      needs btree_gist.
--
--   4. Staff moved out of `users` into `admin_users` (email + password, no
--      phone, no OTP), and `audit_logs` gained `actor_admin_id`.
--
-- Everything else — every table, trigger, append-only guard, CHECK constraint,
-- partial index and view — is carried over unchanged.

-- pg_trgm backs the Hinglish fuzzy-match indexes further down. It is present on
-- the host; postgis and btree_gist are not, hence the changes above.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

