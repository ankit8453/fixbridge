-- ===========================================================================
-- Scope uniqueness, with NULLS NOT DISTINCT.
-- ===========================================================================
--
-- All three depend on Postgres 15+ NULLS NOT DISTINCT, and that is the entire
-- point of them. Under the ordinary rule two NULLs count as different, so a
-- plain unique index would allow exactly the duplicates these exist to forbid:
-- a second platform account silently splitting the platform's income, or two
-- conflicting city-default configs for the same date that the resolver would
-- then pick between arbitrarily.

-- One account per (type, owner). Platform accounts have a NULL owner.
