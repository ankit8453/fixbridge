-- ===========================================================================
-- The double-booking wall.
-- ===========================================================================
--
-- Two customers can tap "book" on the same slot in the same millisecond. No
-- amount of application care can prevent that — a check-then-insert is a race
-- however carefully written, and a Redis lock disappears the moment Redis
-- blinks. So the guarantee lives in the database.
--
-- Previously an `EXCLUDE USING gist` over a derived tstzrange, which refused any
-- *overlapping* pair. That needs btree_gist, which this host does not have.
--
-- This partial unique index refuses two live slots sharing a provider and a
-- start time. See the header note for why that is equivalent given grid-aligned
-- slot generation, and what it stops covering if that ever changes.
--
-- The WHERE clause matters: 'open' and 'blocked' slots are allowed to coexist,
-- which is what makes template regeneration possible.
CREATE UNIQUE INDEX "slots_no_double_booking"
  ON "slots" ("provider_id", "starts_at")
  WHERE "status" IN ('held', 'booked');

